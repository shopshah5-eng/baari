/* Lab module: prescription -> quote -> home collection -> report PDF -> WhatsApp.
   Hard compliance rule: never interpret clinically. Out-of-range values route to
   "doctor se milein" with no diagnosis, no severity, no medicine. */
const fs = require('fs');
const path = require('path');
const S = require('./store');
const WA = require('./wa');
const ETA = require('./eta');

const REPORT_DIR = path.join(__dirname, '..', 'data', 'reports');
const RANGES = {
  'CBC':        [{ k: 'Hemoglobin', lo: 12, hi: 16, unit: 'g/dL' }, { k: 'WBC', lo: 4000, hi: 11000, unit: '/µL' }, { k: 'Platelets', lo: 150000, hi: 410000, unit: '/µL' }],
  'LFT':        [{ k: 'Bilirubin', lo: 0.2, hi: 1.2, unit: 'mg/dL' }, { k: 'SGPT', lo: 7, hi: 56, unit: 'U/L' }, { k: 'SGOT', lo: 8, hi: 33, unit: 'U/L' }],
  'KFT':        [{ k: 'Creatinine', lo: 0.6, hi: 1.3, unit: 'mg/dL' }, { k: 'Urea', lo: 15, hi: 40, unit: 'mg/dL' }],
  'HbA1c':      [{ k: 'HbA1c', lo: 4, hi: 5.6, unit: '%' }],
  'TSH':        [{ k: 'TSH', lo: 0.4, hi: 4.0, unit: 'µIU/mL' }],
  'Lipid profile': [{ k: 'Total Cholesterol', lo: 125, hi: 200, unit: 'mg/dL' }, { k: 'LDL', lo: 50, hi: 100, unit: 'mg/dL' }, { k: 'HDL', lo: 40, hi: 60, unit: 'mg/dL' }],
  'Vitamin D':  [{ k: '25-OH Vitamin D', lo: 30, hi: 100, unit: 'ng/mL' }]
};

/* deterministic pseudo-random values so the demo is reproducible per patient */
function seeded(seed) { let x = 0; for (const ch of String(seed)) x = (x * 31 + ch.charCodeAt(0)) % 100000; return () => (x = (x * 9301 + 49297) % 233280) / 233280; }

function buildValues(collections, seed) {
  const rnd = seeded(seed);
  const out = [];
  for (const test of collections) {
    for (const r of (RANGES[test] || [])) {
      const mid = (r.lo + r.hi) / 2, span = (r.hi - r.lo);
      // 85% in range, 15% just outside — enough to exercise the guard
      const inRange = rnd() > 0.15;
      const v = inRange ? mid + (rnd() - 0.5) * span * 0.8 : (rnd() > 0.5 ? r.hi + span * 0.15 : r.lo - span * 0.1);
      out.push({ test, analyte: r.k, value: +v.toFixed(2), unit: r.unit, lo: r.lo, hi: r.hi, flag: v < r.lo ? 'low' : v > r.hi ? 'high' : 'normal' });
    }
  }
  return out;
}

async function reportPdf(collection, values) {
  const PDF = require('pdfkit');
  const org = S.orgById(collection.org_id);
  const patient = S.load().patients.find(p => p.id === collection.patient_id) || { name: 'Patient', phone: '' };
  fs.mkdirSync(REPORT_DIR, { recursive: true });
  const file = path.join(REPORT_DIR, `report-${collection.id}.pdf`);
  const doc = new PDF({ size: 'A4', margin: 46 });
  const w = doc.page.width - 92;
  doc.fillColor('#0B7A6B').fontSize(22).font('Helvetica-Bold').text(org.name, 46, 46);
  doc.fillColor('#0F1E1B').fontSize(8.5).font('Helvetica')
    .text(`${org.address || org.area || ''} · ${org.phone || ''}`, 46, 74)
    .text('NABL-style reference format · report generated by Baari', 46, 86);
  doc.fontSize(15).font('Helvetica-Bold').text('LABORATORY REPORT', 46, 46, { align: 'right', width: w });
  doc.fontSize(8.5).font('Helvetica').text('Report ID: ' + collection.id.slice(-8).toUpperCase(), { align: 'right', width: w })
    .text('Date: ' + new Date().toLocaleDateString('en-IN'), { align: 'right', width: w });
  let y = 118;
  doc.rect(46, y, w, 46).fill('#E6F4F1').fillColor('#0F1E1B');
  doc.font('Helvetica-Bold').fontSize(10).text('Patient', 56, y + 8).text('Referred by', 300, y + 8);
  doc.font('Helvetica').text(patient.name || 'Patient', 56, y + 24).text('Dr. (self)', 300, y + 24);
  y += 62;
  doc.font('Helvetica-Bold').fontSize(9.5);
  doc.text('TEST', 56, y).text('RESULT', 300, y).text('UNIT', 380, y).text('REFERENCE', 450, y);
  y += 16;
  doc.moveTo(46, y - 4).lineTo(46 + w, y - 4).strokeColor('#DCE7E3').stroke();
  doc.font('Helvetica').fontSize(9.5);
  let lastTest = null;
  for (const v of values) {
    if (v.test !== lastTest) {
      if (y > 700) { doc.addPage(); y = 60; }
      doc.font('Helvetica-Bold').fillColor('#0B7A6B').text(v.test, 56, y); y += 15; doc.font('Helvetica').fillColor('#0F1E1B');
      lastTest = v.test;
    }
    doc.text(v.analyte, 66, y);
    doc.fillColor(v.flag === 'normal' ? '#0F1E1B' : '#D64545').text(`${v.value}`, 300, y);
    doc.fillColor('#0F1E1B').text(v.unit, 380, y).text(`${v.lo} – ${v.hi}`, 450, y);
    y += 15;
    if (y > 720) { doc.addPage(); y = 60; }
  }
  y += 16;
  doc.moveTo(46, y).lineTo(46 + w, y).strokeColor('#DCE7E3').stroke();
  y += 10;
  const abnormal = values.filter(v => v.flag !== 'normal');
  doc.font('Helvetica-Bold').fontSize(9).fillColor('#0F1E1B')
    .text(abnormal.length ? 'Note: kuch values reference range se bahar hain. Kripya doctor se salah lein.' : 'Note: sabhi values reference range me hain.', 46, y, { width: w });
  y += 24;
  doc.font('Helvetica').fontSize(7.5).fillColor('#6B7C78').text(
    'Yeh report sirf jaankari ke liye hai aur kisi doctor ki salah ka vikalp nahi hai. Hum koi diagnosis ya dawa nahi batate.\n' +
    `Verify: ${(process.env.PUBLIC_URL || 'http://localhost:3000')}/verify/${collection.id}`, 46, y, { width: w });
  const buf = await finish(doc);
  fs.writeFileSync(file, buf);
  return file;
}

function finish(doc) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

function createCollection(org, { prescription_id, patient_id, slot_start, slot_end, geo, address_text, technician_id }) {
  const d = S.load();
  d.collections = d.collections || [];
  const c = {
    id: S.id('cl'), org_id: org.id, prescription_id, patient_id, technician_id: technician_id || S.providers(org.id)[0]?.id,
    slot_start: slot_start || new Date(Date.now() + 864e5).setHours(7, 0, 0, 0),
    slot_end: slot_end || new Date(Date.now() + 864e5).setHours(9, 0, 0, 0),
    geo_lat: geo?.lat || null, geo_lng: geo?.lng || null, address_text: address_text || null,
    status: 'scheduled', report_url: null, created_at: new Date().toISOString()
  };
  d.collections.push(c);
  const p = S.load().patients.find(x => x.id === patient_id);
  if (p) WA.send(org, p.phone,
    `✅ *Booking confirm!*\n\n🧪 ${(d.prescriptions || []).find(r => r.id === prescription_id)?.quoted_total ? 'Tests booked' : 'Tests booked'}\n📍 ${address_text || 'Location pin mil gaya'}\n🕖 ${new Date(c.slot_start).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' })}\n💳 Payment: cash / UPI at collection\n\n_Khaali pet aayein. Paani pi sakte hain._`,
    { template: 'collection_booked' });
  S.event(org.id, 'collection_booked', { id: c.id });
  S.save();
  return c;
}

async function uploadReport(org, collectionId) {
  const d = S.load();
  const c = (d.collections || []).find(x => x.id === collectionId && x.org_id === org.id);
  if (!c) return { error: 'collection not found' };
  const rx = (d.prescriptions || []).find(r => r.id === c.prescription_id);
  const tests = rx ? ((rx.vision_json?.tests || []).map(t => t.test)) : ['CBC'];
  const values = buildValues(tests, c.patient_id);
  const file = await reportPdf(c, values);
  c.status = 'reported'; c.report_url = '/media/reports/' + path.basename(file); c.reported_at = new Date().toISOString();
  const abnormal = values.filter(v => v.flag !== 'normal');
  const p = d.patients.find(x => x.id === c.patient_id);
  if (p) {
    WA.send(org, p.phone,
      `📄 *Aapki report taiyar hai!*\n\n${p.name || 'Patient'} · ${new Date().toLocaleDateString('en-IN')}\n${abnormal.length ? 'Kuch values range se bahar hain — doctor se zaroor milein.' : 'Sab values normal range me hain.'}\n\n_Report PDF attach hai. Kabhi bhi clinic se bhi le sakte hain._`,
      { template: 'report_ready', buttons: ['📅 Doctor ka slot', '📄 Report dobara bhejein'] });
    // review ask is a separate, later concern — never bundled with a clinical result
  }
  S.event(org.id, 'report_delivered', { id: c.id, abnormal: abnormal.length });
  S.save();
  return { ok: true, file, values, abnormal: abnormal.length, url: c.report_url };
}

function list(orgId) { return (S.load().collections || []).filter(c => c.org_id === orgId); }
function prescriptions(orgId) { return (S.load().prescriptions || []).filter(p => p.org_id === orgId); }

module.exports = { createCollection, uploadReport, list, prescriptions, reportPdf, buildValues, RANGES };
